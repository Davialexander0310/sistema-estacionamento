    private void botaoExcluir3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoExcluir3ActionPerformed
       String x = JOptionPane.showInputDialog(null, "Quer mesmo excluir? 1 - sim 2 - não");

        int op = Integer.parseInt(x);

        if (op == 1) {
            JOptionPane.showMessageDialog(this, "Cadastro excluido", "Aviso", JOptionPane.WARNING_MESSAGE);

            new TelaMenu_GUI().setVisible(true);
            dispose();
        } else if (op == 2) {
            JOptionPane.showMessageDialog(this, "Cadastro não excluido", "Aviso", JOptionPane.WARNING_MESSAGE);
            new TelaMenu_GUI().setVisible(true);
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Opção inválida", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
        this.dispose();
                                     

    }//GEN-LAST:event_botaoExcluir3ActionPerformed

