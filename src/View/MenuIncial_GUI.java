    public void refreshCap() {
        try {
            Connection conn;
            IniciarBD_DTO.carregarDriver();
            conn = (Connection) DriverManager.getConnection(url, username, password);

            String sql = "SELECT cap_cod, cap_tipo, cap_valor, cap_data FROM CAP;";
            PreparedStatement pst = (PreparedStatement) conn.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();
            tabelaCap.setModel(Cap_DAO.tabelaCap(rs));

            String sqlTotal = "SELECT SUM(cap_valor) FROM CAP " + "WHERE MONTH(cap_data) = MONTH(NOW()) "+ "AND YEAR(cap_data) = YEAR(NOW());";
            PreparedStatement pstTotal = (PreparedStatement) conn.prepareStatement(sqlTotal);
            ResultSet rsTotal = pstTotal.executeQuery();
            if (rsTotal.next()) {
                totalCap.setText("Total este mês: R$ " + String.format("%.2f", rsTotal.getDouble(1)));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }
