    private void salvarVeiculo_BTN1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_salvarVeiculo_BTN1ActionPerformed
        String Placa = placaTelaCadastro_txt1.getText();
        String Marca = marcaTelaCadastro_txt1.getText();
        String Modelo = modeloTelaCadastro_txt1.getText();

        if (Placa.isEmpty() || Marca.isEmpty() || Modelo.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Preencha todos os campos", "Atenção", 1);
            return;
        }

        EmissaoTicket_DAO.imprimir(Placa, Marca, Modelo);
        VeiculoDAO.cadastrar(Placa, Marca, Modelo);

        placaTelaCadastro_txt1.setText("");
        marcaTelaCadastro_txt1.setText("");
        modeloTelaCadastro_txt1.setText("");

        refresh();
    }//GEN-LAST:event_salvarVeiculo_BTN1ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int linhaSelecionada = tabelaVeiculos.getSelectedRow();

        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(null, "Selecione um veículo na tabela!", "Atenção", 1);
            return;
        }

        String placaSelecionada = tabelaVeiculos.getValueAt(linhaSelecionada, 0).toString();

        VeiculoDAO.calcularSaida(placaSelecionada);

        jTextField2.setText("");
        refreshRetirar();
        refreshCar();
    }//GEN-LAST:event_jButton4ActionPerformed

